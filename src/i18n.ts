export const DICTIONARIES: Record<Exclude<Lang, 'en'>, Record<string, string>> = { th: TH };

const PLACEHOLDER = /\{(\w+)\}/g;
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

interface Template {
  re: RegExp;
  names: string[];
  out: string;
}
const templates = new Map<Lang, Template[]>();
function templatesFor(lang: Exclude<Lang, 'en'>): Template[] {
  let list = templates.get(lang);
  if (!list) {
    // Most specific first: "Band {n} colour" must win over "Band {n}", which would also match it.
    const literal = (k: string) => k.replace(PLACEHOLDER, '').length;
    list = Object.entries(DICTIONARIES[lang])
      .filter(([k]) => k.includes('{'))
      .sort(([a], [b]) => literal(b) - literal(a))
      .map(([k, out]) => {
        const names = [...k.matchAll(PLACEHOLDER)].map((m) => m[1]);
        const re = new RegExp(`^${k.split(PLACEHOLDER).map((part, i) => (i % 2 ? '(.+?)' : escapeRe(part))).join('')}$`);
        return { re, names, out };
      });
    templates.set(lang, list);
  }
  return list;
}

/** `text` in `lang`, keeping surrounding whitespace; unknown text is returned unchanged. */
export function translate(text: string, lang: Lang): string {
  if (lang === 'en') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const done = translatePart(trimmed, lang);
  return done === trimmed ? text : text.replace(trimmed, done);
}

function translatePart(text: string, lang: Exclude<Lang, 'en'>): string {
  const exact = DICTIONARIES[lang][text];
  if (exact !== undefined) return exact;
  if (text.includes(' · ')) return text.split(' · ').map((part) => translatePart(part, lang)).join(' · ');
  for (const t of templatesFor(lang)) {
    const m = t.re.exec(text);
    if (m) return t.out.replace(PLACEHOLDER, (_, name: string) => m[t.names.indexOf(name) + 1] ?? '');
  }
  return text;
}

// Values with units, sizes and colours: shown as they are.
const VALUE = /^([-+±→]\s*)?[\d.,×%°:/–\s]+(px|s|Hz|fps|dpi|ms|MB|chars)?$|^#[0-9a-f]{6}$/i;

/** True when `text` has an entry (or is kept as is) in `lang`, part by part. Used by tests and checks. */
export function covered(text: string, lang: Exclude<Lang, 'en'>): boolean {
  const t = text.trim();
  if (!/[A-Za-z]/.test(t) || VALUE.test(t) || KEEP.includes(t) || DICTIONARIES[lang][t] !== undefined) return true;
  if (t.includes(' · ')) return t.split(' · ').every((part) => covered(part, lang));
  return templatesFor(lang).some((tpl) => tpl.re.test(t));
}

/** The language to start with: the saved choice, else Thai for Thai browsers, else English. */
export function initialLang(saved: string | null, browser: readonly string[]): Lang {
  if (saved === 'en' || saved === 'th') return saved;
  return browser.some((l) => l.toLowerCase().startsWith('th')) ? 'th' : 'en';
}
